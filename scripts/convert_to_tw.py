class TaiwanConverter:
    def __init__(self, table_path: Path = TABLE_PATH):
        if not table_path.exists():
            raise FileNotFoundError(f"{table_path} 不存在，請先產生此檔案")
        with open(table_path, "r", encoding="utf-8") as f:
            data = json.load(f)

        self.chars: dict[str, str] = data["characters"]
        self.phrases: dict[str, str] = {}
        self.phrases.update(data.get("st_phrases", {}))
        self.phrases.update(data.get("tw_phrases", {}))

        # 套用自訂規則
        for k, v in CUSTOM_RULES:
            self.phrases[k] = v

        # 臺灣專用字調校
        self.chars["台"] = "台"
        self.chars["群"] = "群"
        self.chars["众"] = "眾"

        # 最大片語長度
        self.max_len = max(len(k) for k in self.phrases.keys())

    def convert_text(self, text: str) -> str:
        if not text or not isinstance(text, str):
            return text

        # 1. 佔位符與俄國潛艦遮罩
        holders: list[str] = []

        def mask_cb(m: re.Match) -> str:
            holders.append(m.group(0))
            return f"\x02{len(holders) - 1}\x03"

        masked = PLACEHOLDER_PAT.sub(mask_cb, text)

        # 2. 正向最大匹配（FMM）轉換
        n = len(masked)
        out: list[str] = []
        i = 0
        while i < n:
            if masked[i] == "\x02":
                end = masked.find("\x03", i)
                if end != -1:
                    idx = int(masked[i + 1:end])
                    out.append(holders[idx])
                    i = end + 1
                    continue
            matched = False
            for l in range(min(self.max_len, n - i), 1, -1):
                sub = masked[i:i + l]
                if sub in self.phrases:
                    out.append(self.phrases[sub])
                    i += l
                    matched = True
                    break
            if not matched:
                c = masked[i]
                out.append(self.chars.get(c, c))
                i += 1

        return "".join(out)

    def convert_json_data(self, data):
        if isinstance(data, dict):
            return {k: self.convert_json_data(v) for k, v in data.items()}
        elif isinstance(data, list):
            return [self.convert_json_data(item) for item in data]
        elif isinstance(data, str):
            return self.convert_text(data)
        return data

    def convert_json_file(self, path: Path, *, dry_run: bool = False) -> int:
        with open(path, "r", encoding="utf-8") as f:
            raw = json.load(f)

        converted = self.convert_json_data(raw)
        if not dry_run:
            with open(path, "w", encoding="utf-8", newline="\n") as f:
                json.dump(converted, f, ensure_ascii=False, indent=2)
                f.write("\n")
        return len(raw) if isinstance(raw, (dict, list)) else 1


